-- (Phase 2b) and converting native-SQL TENANT sites to TenantContext.current()
-- (Phase 2c) follow. Until that rollout is COMPLETE and multi-issuer auth (Phase 3)
-- lands, the app stays single-tenant (all rows = 'default') — no isolation yet.

